type Metadata = {
  currentPage?: number;
  pageSize?: number;
  nextCursor?: string | bigint | Date;
  nextPage?: string;
};

export const config = {
  api: {
    responseLimit: false,
  },
};

const authedOnlyOptions: Array<keyof GetAllModelsInput> = ['favorites', 'hidden'];

/**
 * @ported-to-go feed-go · status: shadow · see ports/manifest.json (id: GET /api/v1/models).
 * Changing this behaviour? Update apps/feed-go/internal/server/v1models.go, apps/feed-go/internal/v1models/serve.go in the same PR; CI lists every port a PR touches.
 * Generated by `node scripts/ports/generate.mjs` from ports/manifest.json: edit the manifest, not this block.
 */
export default MixedAuthEndpoint(handler, ['GET'], { scope: MODEL_VIEW_SCOPE });

async function handler(
  req: NextApiRequest,
  res: NextApiResponse,
  user: Session['user'] | undefined
) {
  if (
    Object.keys(req.query).some((key) =>
      authedOnlyOptions.includes(key as keyof GetAllModelsInput)
    ) &&
    (!user || !requestHoldsScope(req, { scope: TokenScope.CollectionsRead }))
  )
    return res.status(401).json({ error: 'Unauthorized' });

  const parsedParams = modelsEndpointSchema.safeParse(req.query);
  if (!parsedParams.success) return res.status(400).json({ error: parsedParams.error });

  // Check if request is from restricted region and override browsing level
  const region = getRegion(req);
  let browsingLevel = !parsedParams.data.nsfw ? publicBrowsingLevelsFlag : allBrowsingLevelsFlag;
  if (isRegionRestricted(region)) browsingLevel = sfwBrowsingLevelsFlag;
  // Above SFW, the body depends on the caller's region, which the shared cache does not key on.
  if (parsedParams.data.nsfw) res.setHeader('Cache-Control', 'private, no-store');

  // Handle pagination
  const { limit, page, cursor, query, ids: queryIds, ...data } = parsedParams.data;
  let skip: number | undefined;
  const usingPaging = page && !cursor;
  if (usingPaging) {
    if (page && page * limit > 1000) {
      // Enforce new paging limit
      return res
        .status(429)
        .json({ error: "You've requested too many pages, please use cursors instead" });
    }

    ({ skip } = getPagination(limit, page));
  }

  let collectionId: number | undefined;
  if (parsedParams.data.favorites && user) {
    const collections = await getUserBookmarkCollections({ userId: user.id });
    const favoriteModelsCollections = collections.find((c) => c.type === CollectionType.Model);
    collectionId = favoriteModelsCollections?.id;
  }

  // If query is present, do not allow page param
  if (query && page) {
    return res
      .status(400)
      .json({ error: 'Cannot use page param with query search. Use cursor-based pagination.' });
  }

  // feed-go shadow (flag `feed-go-shadow-v1-models`, default off): decided after the cheap rejects.
  // A sampled 200 keeps a reference to the body it writes, and after it its query string, the
  // headers the answer depends on and that body are POSTed to feed-go's internal compare endpoint
  // from `setImmediate`, never awaited. A sample holds nothing until `finish`; one that ends in
  // another status is counted `skipped_status`. Never throws. See `~/server/trpc/feed-go-shadow`.
  // Not sampled: a text `query` (the Meilisearch path) and a signed-in caller, both of which feed-go
  // always answers with a fallback (`v1-models-query`, `v1-models-session`).
  const shadow = query || user ? undefined : beginFeedGoShadowV1Models(req, 'list');
  // This build's Training Data rules, for feed-go's serve path (never awaited, never throws).
  publishTrainingDataRulesLive();

  // The query cursor is an opaque numeric OFFSET, not a model id: Meili's order
  // (relevance, or the caller's sort) is not monotonic in id.
  let searchIds: number[] = [];
  let meiliNextCursor: string | undefined;
  if (query) {
    try {
      const meili = await resolveModelSearchIds({
        query,
        cursor,
        limit,
        browsingLevel,
        types: data.types,
        baseModels: data.baseModels,
        supportsGeneration: data.supportsGeneration,
        // Only a sort the caller named: the schema defaults `sort` to HighestRated,
        // and `sort` is the first ranking rule, so forwarding the default would
        // rank every text search by thumbs-up instead of relevance.
        sort: 'sort' in req.query ? data.sort : undefined,
      });
      searchIds = meili.searchIds;
      meiliNextCursor = meili.nextCursor;
    } catch (e) {
      // Transient model-search backend failure → retryable 503. The service
      // now wraps a transient upstream as ModelSearchMeiliTimeoutError; we ALSO
      // match a raw SDK Meili error that somehow escaped that wrap
      // (isTransientMeiliError) as defense-in-depth — mirroring how
      // /api/v1/users matches BOTH the wrapped signal and isTransientMeiliError.
      // A non-transient error (malformed filter / auth / real app bug) is NOT
      // matched and rethrows to surface as its real status.
      if (e instanceof ModelSearchMeiliTimeoutError || isTransientMeiliError(e)) {
        // Override the public cache headers set by MixedAuthEndpoint —
        // without this Cloudflare caches the 503 and turns a transient
        // Meili brownout into a sticky 503 wall for every other
        // unauthenticated caller with the same query.
        res.setHeader('Cache-Control', 'no-store');
        res.setHeader('Retry-After', '2');
        return res
          .status(503)
          .json({ error: 'Model search is temporarily overloaded — please retry.' });
      }
      throw e;
    }
  }

  try {
    // The download/nextPage URLs need the request origin; resolve it from the
    // same getNextPage call the original endpoint used (pass a placeholder
    // cursor first to obtain baseUrl, then recompute nextPage with the real
    // post-search cursor — getNextPage is pure, so this is cheap and keeps the
    // baseUrl.origin available for runModelSearch's download URLs).
    const baseUrlOrigin = getNextPage({ req }).baseUrl.origin;

    const { items, nextCursor } = await runModelSearch(
      {
        ...data,
        limit,
        skip: !query ? skip : undefined,
        cursor: !query ? cursor : undefined,
        query,
        queryIds,
        searchIds,
        collectionId,
        primaryFileOnly: data.primaryFileOnly === true,
      },
      {
        // PUBLIC endpoint: pass the existing region/nsfw-derived browsingLevel
        // UNCHANGED, and mirror the legacy `?nsfw=true` image-filter widening, except where the
        // region holds the level to SFW.
        browsingLevel,
        nsfwImagePassthrough: !!parsedParams.data.nsfw && !isRegionRestricted(region),
        user: searchViewer(req, user, {
          ownList: !!data.hidden || !!data.followed || !!data.favorites,
          privateListing: data.availability === Availability.Private,
        }),
        baseUrlOrigin,
        redCapable: isRedCapableHost(req.headers.host),
      }
    );

    const effectiveNextCursor = query ? meiliNextCursor : nextCursor;
    const { nextPage } = getNextPage({ req, nextCursor: effectiveNextCursor });
    const metadata: Metadata = { nextCursor: effectiveNextCursor, nextPage };
    if (usingPaging) {
      metadata.currentPage = page;
      metadata.pageSize = limit;
    }

    const body = { items, metadata: { ...metadata } };
    if (shadow) captureFeedGoShadowRest(shadow, body);
    return res.status(200).json(body);
  } catch (e) {
    return handleEndpointError(res, e);
  } finally {
    if (shadow) finishFeedGoShadow(shadow, res.statusCode, res);
  }
}

/**
 * The viewer the search runs as. A narrower credential than a session or a full-scope personal key
 * searches as signed out, except for the caller's own `hidden`, `followed` and `favorites` lists,
 * which are read by their id; those never include their Private models.
 */
function searchViewer(
  req: NextApiRequest,
  user: Session['user'] | undefined,
  { ownList, privateListing }: { ownList: boolean; privateListing: boolean }
) {
  const credential = getRequestCredential(req);
  const viewer = withModeratorRightsFor(user, credential);
  if (!viewer || isSessionOrFullUserKey(credential)) return viewer;
  // The internal system account keeps its rights by id on its own keys.
  if (viewer.isModerator) return viewer;
  return ownList && !privateListing ? viewer : undefined;
}
