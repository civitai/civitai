/**
 * Every Postgres table that holds a user id, and what a personal-data export does with it. A table is
 * either in `REGISTRY` (its rows where a `subject` column is the user are exported) or in `EXCLUDED`
 * with the reason; `__tests__/personal-data-export.registry.test.ts` fails when a model that
 * references a user is in neither, so a new table is a decision, not an omission.
 *
 * Columns are Prisma field names. `subject`: a row is the user's when any of these is the user's id.
 * `staff`: a user id written as `[staff]` unless it is the user. `others`: another user's id, kept as
 * an id. Which columns are read, and how, is `column-policy.ts`.
 */

export type RegistryEntry = {
  subject: readonly string[];
  staff?: readonly string[];
  others?: readonly string[];
  /** A table-specific rule `postgres.ts` applies. */
  rule?: 'image-media' | 'restriction-triggers';
};

