/**
 * RATCHET: reads on the primary database, counted per file.
 *
 * Reads go to the replica (`dbRead`) by default. A read on `dbWrite` is right only when it must
 * see a write the replica may not have yet: read-your-write right after an update, a check that
 * guards a write, a row read under a lock. Those say so with a `// primary: <reason>` comment on
 * the read's line or in the `//` comment lines directly above it. Every other
 * `dbWrite.<model>.findUnique|findUniqueOrThrow|findFirst|findFirstOrThrow|findMany|count|aggregate|groupBy(…)`
 * counts. This freezes the unmarked count per file.
 *
 * Scope: production files under `src/`, test files excluded. Raw SQL on `dbWrite` and reads on a
 * transaction client (`tx.…`) are out of scope. Known gap: a client aliased under another name
 * (`const db = write ? dbWrite : dbRead`) is not followed.
 */

