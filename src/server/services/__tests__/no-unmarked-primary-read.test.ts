const MESSAGE_GROWN =
  'New read on the primary (dbWrite). Read from dbRead (the replica) by default; if this read ' +
  'must see the primary (read-your-write, a check guarding a write), mark it with ' +
  '`// primary: <reason>` on the line above.';
const MESSAGE_SHRUNK =
  'Fewer unmarked dbWrite reads than the baseline records. Lower BASELINE in ' +
  'no-unmarked-primary-read.test.ts to match, in this commit.';

describe('no new unmarked read on the primary (ratchet)', () => {
  it('positive control: unmarked reads count, marked reads and writes do not', () => {
    const count = (src: string) => unmarkedPrimaryReads(parse('x.ts', src), src);
    expect(count('await dbWrite.user.findUnique({ where: { id } });')).toBe(1);
    expect(count('await dbWrite.image\n  .findMany({});\nawait dbWrite.post.count();')).toBe(2);
    expect(count('await dbWrite.model.aggregate({}); await dbWrite.model.groupBy({});')).toBe(2);
    // Marked: same line, the line above, or the run of `//` lines above.
    expect(count('await dbWrite.user.findFirst({}); // primary: read-your-write')).toBe(0);
    expect(count('// primary: guards the update below\nawait dbWrite.user.findFirst({});')).toBe(0);
    expect(count('// primary: lock row\n// more context\nawait dbWrite.user.count();')).toBe(0);
    // A mark needs a reason, and must touch the read.
    expect(count('// primary:\nawait dbWrite.user.count();')).toBe(1);
    expect(count('// primary: x\n\nawait dbWrite.user.count();')).toBe(1);
    // Not a read, not the primary, not code.
    expect(count('await dbWrite.user.update({}); await dbRead.user.findMany({});')).toBe(0);
    expect(count("// dbWrite.user.findMany()\nconst s = 'dbWrite.user.count()';")).toBe(0);
  });

  const current = countAll(productionSources(GLOBS), 'dbWrite', (sf, text) =>
    unmarkedPrimaryReads(sf, text)
  );
  const { grown, shrunk } = diffCounts(current, BASELINE);

  it('no file gains an unmarked dbWrite read', () => {
    expect(grown, MESSAGE_GROWN).toEqual([]);
  });

  it('the baseline matches the code (lower it when a read moves to dbRead or is marked)', () => {
    expect(shrunk, `${MESSAGE_SHRUNK}\nCurrent counts:\n${formatBaseline(current)}`).toEqual([]);
  });
});
