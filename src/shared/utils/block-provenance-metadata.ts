import { FEEDBACK_CAPTURE_METADATA_KEY } from '@civitai/shared/feedback-capture';

/**
 * `Image.metadata` keys that record which App Block app produced an image. They are
 * server-owned: only a server path that has verified the app passes one to `createImage`
 * (its `blockProvenance` argument), and every client-supplied copy is dropped. A new
 * provenance key must be added here together with its writer.
 *
 *  - `blockPublishedAppId`: a workflow output the app published (`persistBlockWorkflowOutputImage`).
 *  - `blockUploadedAppId`: an image the app uploaded from bytes (`persistBlockUploadImage`).
 *  - `blockGenerationSourceAppId`: a workflow output the app kept as a PRIVATE generation source
 *    (`persistBlockGenerationSourceImage`). Never shared, never postable.
 *  - `blockSharedUploadAppId`: a viewer-picked upload the app asked to SHARE with its other viewers
 *    (`persistBlockUploadImage` via `blockImageUpload.persist { share: true }`). Read by the
 *    cross-user gated read only; not postable.
 */
export const BLOCK_PROVENANCE_METADATA_KEYS = [
  'blockPublishedAppId',
  'blockUploadedAppId',
  'blockGenerationSourceAppId',
  'blockSharedUploadAppId',
] as const;

export type BlockProvenanceMetadataKey = (typeof BLOCK_PROVENANCE_METADATA_KEYS)[number];

export function isBlockProvenanceMetadataKey(key: string): boolean {
  return (BLOCK_PROVENANCE_METADATA_KEYS as readonly string[]).includes(key);
}

/**
 * Provenance marker stamped into `Image.metadata` on every image
 * `persistBlockWorkflowOutputImage` publishes — the OauthClient id of the
 * app whose workflow produced it. One of the two keys `getBlockGatedImagesByIds`
 * scopes the cross-user read by (see {@link BLOCK_SHARED_UPLOAD_APP_ID_META_KEY}).
 * Mirrors the `appListingAutogenerated` metadata-provenance precedent in
 * `app-listing-assets.service.ts`.
 */
export const BLOCK_PUBLISHED_APP_ID_META_KEY =
  'blockPublishedAppId' as const satisfies BlockProvenanceMetadataKey;

/**
 * Provenance marker for an image an app UPLOADED from bytes it produced in the viewer's tab
 * (`OPEN_IMAGE_UPLOAD { bytes }`, `blocks.persistAppUploadImage`), stamped by
 * `persistBlockUploadImage`.
 *
 * 🔴 DELIBERATELY A SEPARATE KEY, NOT {@link BLOCK_PUBLISHED_APP_ID_META_KEY} OR
 * {@link BLOCK_SHARED_UPLOAD_APP_ID_META_KEY}. Those scope the CROSS-USER gated read, so stamping
 * either here would let an app read every viewer's bytes uploads with no share and no dialog. This
 * one is accepted only where the reader is already bound to the image's owner: the post-from-app
 * `published` source ({@link BLOCK_POSTABLE_APP_ID_META_KEYS}). It is never readable through the
 * gated read.
 */
export const BLOCK_UPLOADED_APP_ID_META_KEY =
  'blockUploadedAppId' as const satisfies BlockProvenanceMetadataKey;

/**
 * Provenance marker for a VIEWER-PICKED upload (`OPEN_IMAGE_UPLOAD`, `blockImageUpload.persist`) the
 * app asked to SHARE with its other viewers, stamped by `persistBlockUploadImage`. Written
 * ONLY when the request carried `share: true`, the host's dialog told the viewer before they picked
 * that it will be visible to the app's other viewers, and the block token verified with the
 * uploader as its subject. Without the opt-in a picked upload is unstamped and private.
 *
 * Its one reader is the 🔴 CROSS-USER gated read (`getBlockGatedImagesByIds`): THIS app may show the
 * upload to its other viewers, but only once terminally `Scanned`, unflagged, within the viewer's
 * ceiling AND the SFW ceiling (PG / PG-13). Anything else (pending, refused, flagged, mature) is
 * `hidden` with no url, to the uploader too: there is no `ratingPending` owner branch for it.
 *
 * NOT in {@link BLOCK_POSTABLE_APP_ID_META_KEYS}: the viewer agreed to the app's viewers seeing it,
 * not to the app posting it. It never names another app: the value is only ever the appId of a
 * verified block token, `createImage` drops any client-supplied copy, and the reader compares it
 * for equality with the caller's verified appId.
 */
export const BLOCK_SHARED_UPLOAD_APP_ID_META_KEY =
  'blockSharedUploadAppId' as const satisfies BlockProvenanceMetadataKey;

/**
 * Provenance marker for a workflow output an app kept as a PRIVATE generation source
 * (`PERSIST_GENERATION_SOURCE`), stamped by `persistBlockGenerationSourceImage`.
 *
 * 🔴 DELIBERATELY NOT {@link BLOCK_PUBLISHED_APP_ID_META_KEY} AND NOT IN
 * {@link BLOCK_POSTABLE_APP_ID_META_KEYS}. The published key is what puts a row on the app's
 * CROSS-USER shared grid (`getBlockGatedImagesByIds`), and the postable set is what lets the app
 * post it; a private source must reach neither. Its two readers are both bound to the image's
 * owner: the idempotency lookup in `block-generation-source.service.ts`, and the gated read, which
 * resolves a source for its OWN author and the app that kept it only (omitted for anyone else,
 * and for its author too when blocked or held). `block-image-provenance-readers.test.ts` pins
 * that set.
 */
export const BLOCK_GENERATION_SOURCE_APP_ID_META_KEY =
  'blockGenerationSourceAppId' as const satisfies BlockProvenanceMetadataKey;

/**
 * Which output a private generation source was made from, as `<workflowId>#<imageIndex>`: the
 * idempotency key for a repeat `PERSIST_GENERATION_SOURCE`. Not server-owned on its own, so it is
 * only ever read together with {@link BLOCK_GENERATION_SOURCE_APP_ID_META_KEY} (which is) and the
 * row's owner: a row that matches all three was written by `persistBlockGenerationSourceImage`
 * for that viewer.
 */
export const BLOCK_GENERATION_SOURCE_REF_META_KEY = 'blockGenerationSourceRef' as const;

/** The provenance keys a post-from-app `published` source accepts. */
export const BLOCK_POSTABLE_APP_ID_META_KEYS = [
  BLOCK_PUBLISHED_APP_ID_META_KEY,
  BLOCK_UPLOADED_APP_ID_META_KEY,
] as const;

/** A judge's rating in a judge-rated collection (`setCollectionItemNsfwLevel`); it gates approval. */
export const JUDGE_RATING_METADATA_KEY = 'judgeRating';

/**
 * Other server-owned `Image.metadata` keys, dropped from client input the same way:
 *  - `feedbackCapture`: the report a page capture belongs to (`createImage`'s `feedbackCapture`).
 *  - `judgeRating`: see `JUDGE_RATING_METADATA_KEY`.
 *  - `ruleId` / `ruleReason`: the moderation rule that matched the image; whether a removal counts as
 *    a rule's or a moderator's is read from them.
 */
export const OTHER_SERVER_OWNED_IMAGE_METADATA_KEYS = [
  FEEDBACK_CAPTURE_METADATA_KEY,
  JUDGE_RATING_METADATA_KEY,
  'ruleId',
  'ruleReason',
] as const;

const isServerOwnedMetadataKey = (key: string) =>
  isBlockProvenanceMetadataKey(key) ||
  (OTHER_SERVER_OWNED_IMAGE_METADATA_KEYS as readonly string[]).includes(key);

/** Returns `metadata` without any server-owned key; other keys are kept as-is. */
export function stripBlockProvenanceMetadata<T extends Record<string, unknown> | null | undefined>(
  metadata: T
): T {
  if (!metadata || typeof metadata !== 'object') return metadata;
  if (!Object.keys(metadata).some(isServerOwnedMetadataKey)) return metadata;
  return Object.fromEntries(
    Object.entries(metadata).filter(([key]) => !isServerOwnedMetadataKey(key))
  ) as T;
}
