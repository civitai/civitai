// Generates, for each folder `src/server/api-routes/<key>`, the route map that `src/pages/api/<key>/[...path].ts`
// serves it from: `src/server/utils/api-routes/<key>.generated.ts`. One map per key, because a literal
// `import()` is compiled as part of the catch-all that holds it.
//
// The output is committed so a fresh checkout typechecks. `--check` writes nothing and exits 1 when a map is
// stale, missing or left over.

import { existsSync } from 'node:fs';
import { readdir, readFile, rm, writeFile, mkdir } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';

const ROOT = join(fileURLToPath(new URL('.', import.meta.url)), '..');
const SERVED = join(ROOT, 'src', 'server', 'api-routes');
const PAGES = join(ROOT, 'src', 'pages', 'api');
const OUT = join(ROOT, 'src', 'server', 'utils', 'api-routes');
// Next's default pageExtensions: a file with any of these in src/pages is a route.
const PAGE_EXT = /\.(tsx?|jsx?)$/;
const check = process.argv.includes('--check');

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(
    entries.map((entry) => {
      const full = join(dir, entry.name);
      return entry.isDirectory() ? walk(full) : entry.isFile() ? [full] : [];
    })
  );
  return files.flat();
}

const isPage = (dir, name) =>
  ['.ts', '.tsx', '.js', '.jsx'].some((ext) => existsSync(join(dir, name + ext)));

// Each of these would be served wrongly, or not at all, without failing anywhere else.
async function problemsFor(key, routes, files) {
  const pages = join(PAGES, key);
  const problems = [];
  if (!existsSync(join(pages, '[...path].ts'))) {
    problems.push(
      `${key}: src/pages/api/${key}/[...path].ts is missing, so none of its routes is served`
    );
  }
  for (const file of files.filter((f) => /.(tsx|jsx?)$/.test(f))) {
    problems.push(`${key}/${file}: only .ts routes are served; rename it`);
  }
  for (const route of routes) {
    const source = await readFile(join(SERVED, key, route + '.ts'), 'utf-8');
    if (route.includes('[') || /(^|\/)index$/.test(route)) {
      problems.push(
        `${key}/${route}: the catch-all matches exact paths; make it a file in src/pages/api/${key}`
      );
    }
    if (/export\s+const\s+config\b/.test(source)) {
      problems.push(
        `${key}/${route}: \`config\` only applies to a file in src/pages/api/${key}; move it there`
      );
    }
    if (isPage(pages, route) || isPage(join(pages, route), 'index')) {
      problems.push(
        `${key}/${route}: src/pages/api/${key} has the same route, and Next serves that one`
      );
    }
    // Any dynamic route on the way down can capture it, except a plain `[x]` page above its own folder,
    // which matches one segment only.
    const parts = route.split('/').slice(0, -1);
    for (let depth = 0; depth <= parts.length; depth++) {
      const dir = parts.slice(0, depth).join('/');
      if (!existsSync(join(pages, dir))) break;
      for (const entry of await readdir(join(pages, dir))) {
        if (!entry.startsWith('[') || (depth === 0 && entry === '[...path].ts')) continue;
        if (depth < parts.length && /^\[[^.[]/.test(entry) && PAGE_EXT.test(entry)) continue;
        problems.push(
          `${key}/${route}: src/pages/api/${key}/${dir ? dir + '/' : ''}${entry} captures it first`
        );
      }
    }
  }
  return problems;
}

const keys = existsSync(SERVED)
  ? (await readdir(SERVED, { withFileTypes: true }))
      .filter((e) => e.isDirectory())
      .map((e) => e.name)
      .sort()
  : [];
const problems = [];
const outputs = [];
for (const key of keys) {
  const files = (await walk(join(SERVED, key))).map((f) =>
    relative(join(SERVED, key), f).split(sep).join('/')
  );
  const routes = files
    .filter((f) => f.endsWith('.ts'))
    .map((f) => f.slice(0, -3))
    .sort();
  problems.push(...(await problemsFor(key, routes, files)));
  const source = [
    '// GENERATED by scripts/generate-api-routes.mjs — do not edit.',
    "// Re-run 'pnpm run generate:api-routes' after adding, moving or removing a route.",
    '',
    "import type { ApiRoutes } from '~/server/utils/api-router';",
    '',
    'export const routes: ApiRoutes = {',
    ...routes.map((r) => `  '${r}': () => import('~/server/api-routes/${key}/${r}'),`),
    '};',
    '',
  ].join('\n');
  const file = join(OUT, `${key}.generated.ts`);
  outputs.push({
    key,
    file,
    count: routes.length,
    body: prettier.format(source, { ...(await prettier.resolveConfig(file)), filepath: file }),
  });
}
if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(1);
}

let stale = false;
const leftover = existsSync(OUT)
  ? (await readdir(OUT)).filter(
      (f) => f.endsWith('.generated.ts') && !keys.includes(f.replace('.generated.ts', ''))
    )
  : [];
for (const f of leftover) {
  if (check) {
    console.error(
      `api routes: ${f} has no src/server/api-routes folder — run 'pnpm run generate:api-routes'`
    );
    stale = true;
  } else {
    await rm(join(OUT, f));
    console.log(`api routes: removed ${f}`);
  }
}
for (const { key, file, count, body } of outputs) {
  const previous = await readFile(file, 'utf-8').catch(() => null);
  if (previous === body) {
    console.log(`api routes ${key}: up to date (${count})`);
  } else if (check) {
    console.error(`api routes ${key}: STALE — run 'pnpm run generate:api-routes'`);
    stale = true;
  } else {
    await mkdir(OUT, { recursive: true });
    await writeFile(file, body, 'utf-8');
    console.log(`api routes ${key}: wrote ${count}`);
  }
}
if (stale) process.exit(1);
