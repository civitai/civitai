// Custom prisma generator: emits the set of tables that have a Prisma `@updatedAt` column, consumed by
// @civitai/db-queries' updatedAtPlugin so UPDATEs auto-stamp `updatedAt` (Kysely does not, and there is no DB
// trigger). Runs on every `prisma generate` from the same DMMF as prisma-kysely, so the set can't drift from
// the schema. Uses the DB table name (`@@map`) — that's what Kysely/the plugin match on.

import PrismaGenHelper from '@prisma/generator-helper';
import fs from 'node:fs/promises';
import path from 'node:path';

const header = `// This file was generated by a custom prisma generator, do not edit manually.\n`;

PrismaGenHelper.generatorHandler({
  onManifest() {
    return {
      defaultOutput: './updated-at-tables.ts',
      prettyName: '@updatedAt table set',
    };
  },
  async onGenerate(options) {
    const tables = options.dmmf.datamodel.models
      .filter((m) => m.fields.some((f) => f.isUpdatedAt))
      .map((m) => m.dbName ?? m.name) // `dbName` = the @@map'd table name
      .sort();

    const body =
      `import type { DB } from './types';\n\n` +
      `// Tables with a Prisma \`@updatedAt\` column. Passed to updatedAtPlugin so an UPDATE to one of these\n` +
      `// auto-stamps \`updatedAt\`. Typed as \`keyof DB\` so a name that isn't a real Kysely table is a compile\n` +
      `// error (a cross-check against prisma-kysely's output).\n` +
      `export const UPDATED_AT_TABLES = new Set<keyof DB>([\n` +
      // Single-quoted to match the repo's Prettier config (table names are plain identifiers), so the
      // generated file is Prettier-clean and doesn't churn on format/regenerate.
      tables.map((t) => `  '${t}',`).join('\n') +
      `\n]);\n`;

    const outputFile = options.generator.output;
    if (!outputFile || !outputFile.value) {
      throw new Error('No output file specified');
    }
    const outputPath = path.resolve(outputFile.value);
    await fs.mkdir(path.dirname(outputPath), { recursive: true });
    await fs.writeFile(outputPath, header + body, 'utf-8');
  },
});
