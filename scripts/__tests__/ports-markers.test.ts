import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';

import { describeDrift, plan } from '../ports/generate.mjs';
import { applyMarkers, stripMarkers } from '../ports/markers.mjs';

// The `@ported-to-go` markers (scripts/ports/markers.mjs) and the generator's check mode
// (scripts/ports/generate.mjs) on a fixture repo.

const ROUTER = `import { portedHandler, otherHandler } from './handlers';

export const appRouter = router({
  /** An existing doc comment stays where it is. */
  ported: proc.query(portedHandler),
  other: proc.query(otherHandler),
});
`;

const port = (over: Record<string, unknown> = {}) => ({
  id: 'app.ported',
  kind: 'trpc',
  service: 'feed-go',
  status: 'shadow',
  routes: ['/api/trpc/app.ported'],
  nodeEntry: { file: 'src/router.ts', symbol: 'appRouter.ported' },
  goHandler: ['apps/feed-go/internal/server/handler.go'],
  flags: { shadow: 'fx-shadow-flag', transport: null, probe: null },
  holdout: null,
  soak: null,
  ...over,
});

const MARKED = `import { portedHandler, otherHandler } from './handlers';

export const appRouter = router({
  /** An existing doc comment stays where it is. */
  /**
   * @ported-to-go feed-go · status: shadow · see ports/manifest.json (id: app.ported).
   * Changing this behaviour? Update apps/feed-go/internal/server/handler.go in the same PR; CI lists every port a PR touches.
   * Generated by \`node scripts/ports/generate.mjs\` from ports/manifest.json: edit the manifest, not this block.
   */
  ported: proc.query(portedHandler),
  other: proc.query(otherHandler),
});
`;

describe('applyMarkers', () => {
  it('writes the marker directly above the entry symbol, at its indentation', () => {
    expect(applyMarkers(ROUTER, 'src/router.ts', [port()])).toBe(MARKED);
  });

  it('is idempotent', () => {
    expect(applyMarkers(MARKED, 'src/router.ts', [port()])).toBe(MARKED);
  });

  it('rewrites a stale marker in place rather than adding a second', () => {
    const ramped = applyMarkers(MARKED, 'src/router.ts', [port({ status: 'ramp' })]);
    expect(ramped).toBe(MARKED.replace('status: shadow', 'status: ramp'));
  });

  it('removes the marker of a port that is no longer in the manifest, restoring the file', () => {
    expect(applyMarkers(MARKED, 'src/router.ts', [])).toBe(ROUTER);
  });

  it('moves a marker written above the wrong symbol to the right one', () => {
    const wrong = ROUTER.replace(
      '  other:',
      `${MARKED.split('\n').slice(4, 9).join('\n')}\n  other:`
    );
    expect(wrong).not.toBe(MARKED);
    expect(applyMarkers(wrong, 'src/router.ts', [port()])).toBe(MARKED);
  });

  it('marks a default export', () => {
    const text = "import { h } from './h';\n\nexport default wrap(h);\n";
    const out = applyMarkers(text, 'src/route.ts', [
      port({
        id: 'GET /api/fx',
        kind: 'rest',
        nodeEntry: { file: 'src/route.ts', symbol: 'default' },
      }),
    ]);
    expect(out.split('\n').slice(2, 4)).toEqual([
      '/**',
      ' * @ported-to-go feed-go · status: shadow · see ports/manifest.json (id: GET /api/fx).',
    ]);
    expect(out.split('\n')[7]).toBe('export default wrap(h);');
  });

  it('reports a hand-written marker outside the generated block shape', () => {
    const text = `${ROUTER}/** @ported-to-go feed-go · status: shadow */\nexport const x = 1;\n`;
    expect(stripMarkers(text).malformed).toEqual([8]);
  });
});

// A fixture repo with the real schema, a fake `go list`, and git (the generator finds stray
// markers with `git grep`).
let root: string;
afterEach(() => rmSync(root, { recursive: true, force: true }));

const SCHEMA = resolve(__dirname, '../../ports/manifest.schema.json');
const put = (rel: string, text: string) => {
  mkdirSync(dirname(join(root, rel)), { recursive: true });
  writeFileSync(join(root, rel), text);
};
const git = (...args: string[]) => execFileSync('git', args, { cwd: root, encoding: 'utf8' });
const goList = () => '';

function repo() {
  root = mkdtempSync(join(tmpdir(), 'ports-gen-'));
  put('src/router.ts', ROUTER);
  put('src/handlers.ts', 'export const portedHandler = 1;\nexport const otherHandler = 2;\n');
  put('src/elsewhere.ts', 'export const elsewhere = 1;\n');
  put('src/server/flipt/client.ts', "export enum F { S = 'fx-shadow-flag' }\n");
  put('apps/feed-go/go.mod', 'module example.com/fx\n');
  put('apps/feed-go/internal/server/handler.go', 'package server\n');
  put('ports/manifest.json', JSON.stringify({ ports: [port()] }));
  mkdirSync(join(root, 'ports'), { recursive: true });
  copyFileSync(SCHEMA, join(root, 'ports/manifest.schema.json'));
  git('init', '-q');
  git('add', '.');
}

function write(result: ReturnType<typeof plan>) {
  writeFileSync(join(root, 'ports/manifest.json'), result.manifestAfter);
  for (const [rel, { after }] of result.files) writeFileSync(join(root, rel), after);
  git('add', '.');
}

describe('generator check mode', () => {
  it('is clean right after a write, and only then', () => {
    repo();
    const first = plan(root, { goList });
    expect(first.errors).toEqual([]);
    expect(describeDrift(first)).toEqual([
      'ports/manifest.json: port app.ported nodeDeps: +2 -0\n    + src/handlers.ts\n    + src/router.ts',
      'ports/manifest.json: port app.ported goDeps: +2 -0\n    + apps/feed-go/go.mod\n    + apps/feed-go/internal/server/handler.go',
      'src/router.ts: missing marker for port app.ported',
    ]);
    write(first);
    expect(describeDrift(plan(root, { goList }))).toEqual([]);
    expect(readFileSync(join(root, 'src/router.ts'), 'utf8')).toBe(MARKED);
  });

  it('flags a marker moved to the wrong symbol', () => {
    repo();
    write(plan(root, { goList }));
    const block = MARKED.split('\n').slice(4, 9).join('\n');
    put('src/router.ts', ROUTER.replace('  other:', `${block}\n  other:`));
    git('add', '.');
    expect(describeDrift(plan(root, { goList }))).toEqual([
      'src/router.ts: marker on the wrong line',
    ]);
  });

  it('flags a stale marker after a status change in the manifest', () => {
    repo();
    write(plan(root, { goList }));
    const m = JSON.parse(readFileSync(join(root, 'ports/manifest.json'), 'utf8'));
    m.ports[0].status = 'ramp';
    m.ports[0].flags.transport = 'fx-shadow-flag';
    put('ports/manifest.json', JSON.stringify(m, null, 2) + '\n');
    expect(describeDrift(plan(root, { goList }))).toEqual([
      'src/router.ts: stale marker for port app.ported',
    ]);
  });

  it('flags a marker on a file the manifest does not name', () => {
    repo();
    write(plan(root, { goList }));
    const block = MARKED.split('\n').slice(4, 9).join('\n').replace(/^ {2}/gm, '');
    put('src/elsewhere.ts', `${block}\nexport const elsewhere = 1;\n`);
    git('add', '.');
    expect(describeDrift(plan(root, { goList }))).toEqual([
      'src/elsewhere.ts: marker for app.ported, which is not a port of this file',
    ]);
  });

  it('reports a manifest the schema rejects and writes no markers', () => {
    repo();
    put('ports/manifest.json', JSON.stringify({ ports: [port({ status: 'live' })] }));
    const result = plan(root, { goList });
    expect(result.errors).toEqual([
      'schema /ports/0/status: must be equal to one of the allowed values',
    ]);
    expect(result.files.size).toBe(0);
  });
});
